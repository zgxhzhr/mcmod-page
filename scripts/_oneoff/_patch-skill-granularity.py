#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""把「模组页只写摘要，细节归资料页」这条红线写进规则块。

起因：2026-11-13 另一台 AI 读完拆分后的 skill 交付了一页怪物娘模组介绍，
结构全对（1 个 h1 + 4 个 h2、无 ban、前置不带版本号），
但仍然把「邪恶砂轮的每档产出片数」和「23 种生物各自的收服条件」写进了模组页 ——
因为这条规则从来没写进 skill，只存在于审核附言里。

教训：审核附言里出现的规则，必须当天进规则块，否则下一台机器照样踩。
"""
from pathlib import Path

ROOT = Path(r"E:\Mod\模板与工具\发布\mcmod-page")
TARGET = ROOT / "rules" / "02-模组页.md"

SECTION = '''## ⚠️ 红线：模组页只写摘要，细节归资料页

审核原话（已退过至少三次）：

> （部分含有）**对单个资料过于详细的介绍需要写到对应的物品里，模组正文仅需摘要**

这条是模组页最容易踩的一条，而且**结构全对也照样退**。

### 该下沉的特征

一段话里出现下面任一特征，就该搬到对应资料页：

| 特征 | 例子 |
|---|---|
| 只讲某一个物品/方块的产出、耐久、概率 | 三档战利品箱分别拆出 1、3、6 片…牛头人之锤拆 8 片 |
| 只讲某一个实体的特殊机制或触发条件 | 女鬼要身边摆 8 朵凋零玫瑰、玩家自身带上凋零效果 |
| 只讲某一条状态效果的获得方式 | 蚂蚁信息素由收服后的工兵蚁定期赋予主人 |
| 数字很多但都是同一个对象的参数 | 血量分 8 档逐档锁定 |

### 该留在模组页的

| 内容 | 为什么留 |
|---|---|
| 多个对象的分类概览 | 「分三类」「共 23 种」——这是模组级结构 |
| 全族共用的机制 | 好感度、经验等级、饰品栏、交易体系 |
| 前置、兼容、配置项 | 影响能不能跑，属于模组层面 |
| 一句话定位 | 「本模组是 X 的 Y 扩展」 |

### 检验问句（交付前必答）

> 把这段单独抽出来，贴到那个物品/实体自己的页面上，读者会觉得错位吗？

**不觉得错位 → 它本来就是资料页的内容。**

### 判据：数一下主体数

```
一段话里出现的「被描述对象」有几个？
  ≥2 个  → 这是模组级概览，留在模组页
  =1 个  → 这是资料页的内容，下沉
```

### 具体改法

| 反例（写在模组页） | 改成 |
|---|---|
| 「三档战利品箱分别拆出 1、3、6 片，普通武器 2 片…」整段产出表 | 一句概括「产出量按战利品档次递增，从低档的 1 片到半身像的 12 片」，明细进砂轮物品页 |
| 23 种生物的收服条件逐条写 | 一张三行的表（额外条件类型 / 涉及生物 / 要做什么）+ 两个特例，明细进各实体页 |

### 资料页还没建怎么办

允许先在模组页承接，但必须：

1. **表格化**（散文式的逐条列举最容易被判「碎」）
2. 交付说明里注明「这些数值待拆到 XX 资料页」
3. 尽快把资料页建起来，之后回删

### 真实案例（2026-11-13）

一台 AI 读完拆分后的 skill 交付了怪物娘模组介绍：结构完全合规，
但把砂轮的六档产出片数、23 种生物的收服条件全写进了模组页 —— 仍会被退。
**原因不是模型不听话，是这条规则当时不在 skill 里。**
审核附言里出现过的规则，必须当天进规则块。

---

'''

def main() -> int:
    t = TARGET.read_text(encoding="utf-8")
    if "红线：模组页只写摘要" in t:
        print("已存在，跳过")
        return
    # 插在文件头（--- 分隔线之后）
    marker = "> §编号与 SKILL.md 一致，可按编号交叉引用。\n\n---\n\n"
    i = t.find(marker)
    if i < 0:
        print("找不到文件头标记")
        return
    pos = i + len(marker)
    t = t[:pos] + SECTION + t[pos:]
    TARGET.write_text(t, encoding="utf-8")
    print(f"✓ 已写入 rules/02-模组页.md，{len(t.split(chr(10)))} 行")


if __name__ == "__main__":
    raise SystemExit(main())
