# -*- coding: utf-8 -*-
"""把「一个页面只应有一个 h1」写进 skill，并修掉之前的误导。"""
from pathlib import Path

SKILL = Path(r"E:\Mod\模板与工具\发布\mcmod-page\SKILL.md")

SECTION = '''### 6.2.2.35 一个页面只有第一个 h1，其余分节用 h2

**踩过的坑**：因为之前被「跨级标题」退过，矫枉过正，把所有分节都写成 `[h1=]`，
一个页面出现 4~8 个一级标题。审核指出「应为 h2」。

#### 规则

```
第 1 个 [h1=]  = 页面主标题（概述 / 简介 / 介绍）
之后的所有分节  = [h2=]
```

原文自带多个 h1 时（常见的是 `[h1=概述]` + `[h1=画廊]`），**这些保留不动**——
那是作者本来就有的结构，改动会破坏原稿。只把自己新增的节压成 h2。

#### 对照

| 写法 | 判断 |
|---|---|
| `[h1=概述]` + `[h2=内容]` + `[h2=合成]` | ✓ 正确 |
| `[h1=概述]` + `[h1=画廊]` + `[h2=内容]` | ✓ 原文的两个 h1 保留，新增用 h2 |
| `[h1=概述]` + `[h1=内容]` + `[h1=合成]` | ✗ 全是 h1，审核会指 |
| `[h2=概述]` 开头 | ✗ 跨级（没有父级 h1）|

#### 为什么不是「全 h1」

- h1 是页面**唯一**的主标题层级，多个 h1 等于多个主标题，结构上没有从属关系
- h1 越大越好读是错觉：8 个并列的一级标题，目录树是平的，看不出哪个是主干
- 真正的层级是「页面 → 章节」，一个 h1 就够了

#### 与 §6.2.2.33（标题分层）的区别

| 节 | 讲什么 |
|---|---|
| **§6.2.2.33** | 哪些内容值得配标题（省掉一句话的尾巴）|
| **§6.2.2.35** | 配了标题之后，用 h1 还是 h2 |

两条要一起用：先按 33 决定「这节要不要标题」，再按 35 决定「用几级」。

#### 与 §6.2.2.31.1（短介绍 ban）的关系

压成 h2 之后，`h1` 的数量自然变成 1，`[ban:title_menu]` 的判断要按**标题总数**（h1+h2）重新看：

```
字数 < 600 且 标题总数 ≤ 3   → 加 ban
否则                        → 不加，让目录显示
```

实例：Mine & Slash Expansion 5180 是 1231 字、1 个 h1 + 7 个 h2，
标题充足，**不该 ban**；之前有 ban 是错的，已去掉。

'''

def main():
    t = SKILL.read_text(encoding="utf-8")
    if "6.2.2.35 一个页面只有第一个 h1" in t:
        print("已存在，跳过")
        return
    anchor = "### 6.2.3 `remark`（附言）写什么、不写什么"
    if anchor not in t:
        print("找不到锚点")
        return
    t = t.replace(anchor, SECTION + anchor, 1)
    SKILL.write_text(t, encoding="utf-8")
    print("✓ 已写进 skill §6.2.2.35")


if __name__ == "__main__":
    main()
