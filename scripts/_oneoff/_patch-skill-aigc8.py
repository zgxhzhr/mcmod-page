SECTION = '''

### 10.2.3 AIGC 痕迹八条判据（审核判「严重」的真实案例）

**案例**：动物谷：猫猫狗狗（3863）的模组页。审核判「严重 AIGC 痕迹」。
后来有人改了一版，实质差异只有三处错别字：

```
animal谷本体 → 动物谷本体
向购买取得   → 向他购买取得
小鸡         → 鸡
```

**句式、段落模板、表格排布一字未动，审核照样判严重。**
说明审核看的是句法与段落结构。**改错别字不算改。**

#### ① 段落结构同构（最致命）

```
品种          → 一句总述 + 表格 + 一句补充
行为与驯服     → 一句总述 + 三条要点 + 一句补充
饲养与装饰方块  → 一句总述 + 表格 + 一句补充
宠物商人      → 一句总述 + 一句补充
```

四节用同一个「总述 → 列举 → 补充」模具。人写百科节奏是乱的：
有的节一句话就够，有的节要展开。**整齐得像模板，就是最硬的指纹。**

#### ② 补齐型对仗（「不 X，而 Y」的四个变体）

| 原文 | 变体 |
|---|---|
| 它**不引入**新的驯养系统，**沿用**动物谷本体的喂食与驯服机制 | 不引入 X，沿用 Y |
| 攻击**只针对**动物，**不针对**玩家 | 只针对 X，不针对 Y |
| 猫与犬科**共用**一套行为框架，**区别只在**攻击目标 | 共用 X，区别只在 Y |
| **其中**宠物碗与几处睡床有实际作用，**其余只作**装饰 | 其中 X 有用，其余 Y |

一句话里同时出现肯定与否定两个半句，就是同一个语法模具。
和 §10.2.1 的「不是 X 而是 Y」是同族，只是把「不是」换成了「不引入 / 只针对 / 共用 / 其中」。

#### ③ 「除了…还…」递进

> **除了动物**，模组**还加入了** 7 种饲养与装饰方块，**以及**一个专门卖猫狗的宠物商人村民。

三项并列 + 递进连接词，一句话塞完所有新增内容。

#### ④ 完整性宣言

> 此模组把猫和狗**做成了完整的一套**
> 8 个猫品种、15 个犬科品种，**每个品种都有**成年公、成年母与幼崽三种形态

用「完整」「每个都…」证明覆盖面，而不是陈述事实。

#### ⑤ 比喻化收尾（这次校正的）

> 狗跟着玩家走时，羊也会跟着狗，**等于一个会自己走路的赶羊器**。

以前把它当「像人写的好句子」，实际上**它也是 AIGC 特征**：
机制已经说清楚（狗走、羊跟）了，多出来的比喻是**为了好听而加的**。
跟「替寄件人完成最后一步」同一类。

#### ⑥ 最高级强调

> **德国牧羊犬**是**唯一的特例**

「唯一」「最」「典型」这类最高级，是给事实加价值判断。

#### ⑦ 表格同一列几乎全同

品种表第二列 20 行写「宠物商人」，只有 3 行是「自然生成」。
人一般会合并成一句话（「除豹猫、狼、狐狸外均需购买」）或改列结构。

#### ⑧ 版本信息节

```
版本信息
当前版本 1.0.0.28，对应 Minecraft 1.12.2。前置为动物谷:基本（Animania）。
```

违反 §6.2.2.3；前置信息应该进「前置」节。

#### 改法示范

```
✗ 它不引入新的驯养系统，沿用动物谷本体的喂食与驯服机制。
✓ 驯养沿用动物谷本体的喂食与驯服机制。

✗ 猫与犬科共用一套行为框架，区别只在攻击目标。
✓ 两者的行为逻辑相同，攻击目标不同：猫打小型动物，犬科打山羊、绵羊与兔子。

✗ 狗跟着玩家走时，羊也会跟着狗，等于一个会自己走路的赶羊器。
✓ 狗移动时，附近的羊与山羊会跟着它一起走。
```

**规律**：删掉补齐的后半句，句子更短，信息一条没少。
那些「不 X 而 Y」的补语，读者并不需要。

#### 自检清单

```
□ 四节以上的页面，各节的段落形状是否一样？
□ 有没有「不X而Y / 只X不Y / 共用X区别在Y / 其中X其余Y」？
□ 有没有「除了…还…以及…」一句三并列？
□ 有没有「完整的一套 / 每个都 / 唯一 / 最」这类价值判断？
□ 有没有为了好听加的比喻？
□ 有没有一列全是同一个值的表格？
```

'''

