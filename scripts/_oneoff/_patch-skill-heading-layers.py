#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把「标题分层」的判据写进 skill。"""
from pathlib import Path

SKILL = Path(r"E:\Mod\模板与工具\发布\mcmod-page\SKILL.md")

SECTION = '''### 6.2.2.33 标题要按「读者会不会跳着找」分，不要一节一个 h1

长介绍用 `[h1=]` 分节是对的，但**不是每一节都值得占一个目录项**。

#### 判据

| 这一节 | 配标题吗 | 理由 |
|---|---|---|
| 读者会主动跳过去找（分类、获取方式、数值表）| **配 `[h1=]`** | 目录要能直达 |
| 正文顺序读的说明段（机制解释、原理）| 看长度：≥150 字配 h1，否则加粗 | 短了跳过去只有两行，反而别扭 |
| 一句话的尾巴（技能、版本、作者、致谢）| **加粗，不配标题** | 占目录项没有信息价值 |

两条可以直接用的线：

```
每节 < 100 字、只有一两句        → 不配标题，用 <strong> 起头挂在上一节末尾
每节 ≥ 150 字，或含表格/列表      → 配 [h1=]
```

#### 实例（Malstone 26143）

改前 6 个 h1，753 字，平均每节 125 字，其中「技能」30 字、「版本」30 字各占一个一级目录：

```
h1 概述 / h1 分类 / h1 与灵灾的关系 / h1 新增属性 / h1 技能 / h1 版本
```

改后 4 个 h1 + 2 个加粗段：

```
h1 概述            ← 原文文字 + 图 + 数量说明
h1 分类            ← 表格，读者会查
h1 与灵灾的关系     ← 200 字，读者会跳
h1 新增属性         ← 表格，读者会查
   <strong>技能</strong>：…         ← 30 字，挂末尾
   <strong>版本</strong>：…         ← 30 字，挂末尾
```

目录从 6 项降到 4 项，没有信息损失。

#### 为什么不用 h2

用 `[h2=]` 虽然能避开「一节一个 h1」的笨重，但它要求前面有 `[h1=]` 父级，
资料页与原文无标题的模组页都没有这个父级，一用就跨级。
**缩短尾巴的办法是加粗，不是降一级标题。**

#### 另一个方向：短页面干脆合并

如果整篇只有 300~500 字，也可以只留 `[h1=概述]` + `[h1=内容]` 两个标题，
其余全用加粗分段——比四个目录项指向短段落更自然。

'''

def main():
    t = SKILL.read_text(encoding="utf-8")
    if "6.2.2.33 标题要按" in t:
        print("已存在，跳过")
        return
    anchor = "### 6.2.3 `remark`（附言）写什么、不写什么"
    if anchor not in t:
        print("找不到锚点")
        return
    t = t.replace(anchor, SECTION + anchor, 1)
    SKILL.write_text(t, encoding="utf-8")
    print("✓ 已写进 skill §6.2.2.33")


if __name__ == "__main__":
    main()
