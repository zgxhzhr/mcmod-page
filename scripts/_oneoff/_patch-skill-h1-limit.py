#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把「h1 数量上限」与「版本信息一律不写」写进 skill。"""
from pathlib import Path

SKILL = Path(r"E:\Mod\模板与工具\发布\mcmod-page\SKILL.md")

SECTION = '''### 6.2.2.34 h1 不要铺满全篇：超过三个就停下重新划

`[h1=]` 是最重的层级，用多了页面会碎。**三个以上 h1 必须自检：真的需要这么多吗？**

#### 判据

```
h1 数量 ≤ 2     正常，不用想
h1 数量 = 3     边界，检查每节是否 ≥150 字
h1 数量 ≥ 4     必须重划：合并、降级加粗，或删掉不必要的节
```

配合 §6.2.2.33 的两条线一起用：

```
每节 < 100 字、只有一两句        → 不配标题，用 <strong> 起头
每节 ≥ 150 字，或含表格/列表      → 配 [h1=]
```

#### 症状：页面出现「一屏一个 h1」

实例（Canned Food and Drinks 14363，改前 4 个 h1，499 字）：

```
h1 概述            ~150 字
h1 空罐子          ~120 字 + 1 张表
h1 罐装食品与果汁   ~250 字
h1 版本            ~30 字      ← 违规，且只有一句话
```

改后 3 个 h1，版本节整节删除（见 §6.2.2.3）：

```
h1 概述
h1 空罐子
h1 罐装食品与果汁
```

#### 三个降级手段

| 手段 | 用在什么情况 |
|---|---|
| **删** | 这节本来就不该写（版本、作者、协议）——见 §6.2.2.3 |
| **降为加粗** | 尾声性质、一两句话（历史、技能、致谢） |
| **合并** | 两节在讲同一件事的两面（「来源」+「获取方式」→「获取」） |

**不能用的手段**：降成 `[h2=]`。资料页与原文无标题的模组页没有 `[h1=]` 父级，
一用 h2 就跨级；有 h1 父级的页面用 h2 分节是对的，但那是「本来就有 h1」的情况，
不是拿来给自己多加的标题降级的。

#### 自查命令

```powershell
python E:\\Mod\\模板与工具\\发布\\mcmod-page\\scripts\\check-page-structure.py 草稿.html
```

它会报出标题数量与层级。**看到「4 个」以上的 h1，先停手重划，别急着提交。**

'''

def main():
    t = SKILL.read_text(encoding="utf-8")
    if "6.2.2.34 h1 不要铺满全篇" in t:
        print("已存在，跳过")
        return
    anchor = "### 6.2.3 `remark`（附言）写什么、不写什么"
    if anchor not in t:
        print("找不到锚点")
        return
    t = t.replace(anchor, SECTION + anchor, 1)
    SKILL.write_text(t, encoding="utf-8")
    print("✓ 已写进 skill §6.2.2.34")


if __name__ == "__main__":
    main()
